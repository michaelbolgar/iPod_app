import UIKit

/// эти цвета можно использовать в вёрстке
/// человек, ответственный за Design System, поменяет цвета по ходу выполнения задачи, не мешая другим членам команды
public enum AppColor {
    public static let primary = UIColor.systemYellow
    public static let secondary = UIColor.systemGray
    public static let white = UIColor.white
    public static let background = UIColor.black
}
